test('corrige exactamente los 104 saldos y 10 IMEI de la carga original, con respaldo completo antes/después', async () => {
  assert.equal(rows.length, 114);
  const beforeState = await snapshot();
  await db.exec(correction);
  const afterState = await snapshot();
  const expected = structuredClone(beforeState);
  const costByProduct = new Map(beforeState.movimientos
    .filter(m => m.referencia_id === reference).map(m => [m.producto_id, m.costo]));
  for (const item of expected.stock) {
    if (item.tienda_codigo === 'CK-01' && costByProduct.has(item.producto_id)) item.precio_tienda = costByProduct.get(item.producto_id);
  }
  for (const item of expected.unidades) {
    if (item.tienda_actual === 'CK-01' && costByProduct.has(item.producto_id)) item.precio_tienda = costByProduct.get(item.producto_id);
  }
  const correctedAudit = afterState.audit.filter(a => a.accion === action);
  assert.equal(correctedAudit.length, 1);
  assert.deepEqual({ ...afterState, audit: afterState.audit.filter(a => a.accion !== action), respaldo: null }, expected);

  const detail = correctedAudit[0].detalle;
  assert.equal(detail.stock_corregidos, 104);
  assert.equal(detail.serializados_corregidos, 10);
  assert.equal(detail.referencias, 114);
  assert.equal(detail.unidades, 1372);
  assert.equal(detail.valoracion_erronea, 28934000);
  assert.equal(detail.costo_original_corregido, 13107200);
  assert.equal(detail.import_reference, reference);
  assert.equal(detail.source_audit_id, beforeState.audit[0].id);
  assert.equal(detail.respaldo_registro_id, batch);
  assert.equal(detail.antes, undefined, 'Los costos e IMEI completos no se publican en audit_log');
  assert.equal(detail.despues, undefined);
  assert.equal(afterState.respaldo.length, 1);
  const backup = afterState.respaldo[0];
  assert.equal(backup.registro_id, batch);
  assert.equal(backup.detalle.source_audit_id, beforeState.audit[0].id);
  assert.equal(backup.detalle.import_reference, reference);
  assert.equal(backup.detalle.antes.length, 114);
  assert.equal(backup.detalle.despues.length, 114);
  for (let i = 0; i < backup.detalle.antes.length; i++) {
    const previous = backup.detalle.antes[i];
    const current = backup.detalle.despues[i];
    assert.equal(current.producto_id, previous.producto_id);
    assert.equal(current.unidad_id, previous.unidad_id);
    assert.equal(previous.inventario_antes.precio_tienda, previous.precio);
    assert.deepEqual(current.inventario, { ...previous.inventario_antes, precio_tienda: previous.costo });
    assert.deepEqual(previous.movimiento_antes, beforeState.movimientos.find(m => m.id === previous.id));
    assert.deepEqual(previous.producto_antes, beforeState.productos.find(p => p.id === previous.producto_id));
  }
  const affectedStock = afterState.stock.filter(s => s.tienda_codigo === 'CK-01' && costByProduct.has(s.producto_id));
  const affectedUnits = afterState.unidades.filter(u => u.tienda_actual === 'CK-01' && costByProduct.has(u.producto_id));
  assert.equal(affectedStock.reduce((sum, s) => sum + s.cantidad, 0) + affectedUnits.length, 1372);
  assert.equal(affectedStock.reduce((sum, s) => sum + s.cantidad * s.precio_tienda, 0)
    + affectedUnits.reduce((sum, u) => sum + u.precio_tienda, 0), 13107200);
  assert.equal((await db.query("select relrowsecurity from pg_class where oid='kora_private.respaldo_costos_fusion_tolu_20260919'::regclass")).rows[0].relrowsecurity, true);
  for (const role of ['anon', 'authenticated', 'service_role']) {
    assert.equal((await db.query("select has_table_privilege($1,'kora_private.respaldo_costos_fusion_tolu_20260919','SELECT') as allowed", [role])).rows[0].allowed, false);
  }
});

