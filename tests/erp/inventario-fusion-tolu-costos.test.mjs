for (const [description, mutation, error] of guardCases) {
  test(`se detiene sin escrituras parciales: ${description}`, async () => {
    await db.exec(mutation);
    const state = await snapshot();
    await assert.rejects(db.exec(correction), error);
    await db.exec('rollback');
    assert.deepEqual(await snapshot(), state);
  });
}

test('una modificación inesperada de un trigger revierte también los 104 costos ya actualizados', async () => {
  await db.exec(`create function prueba_mutacion_no_permitida() returns trigger language plpgsql as $$
    begin new.imei := 'alterado-' || new.imei; return new; end $$;
    create trigger prueba_mutacion_no_permitida before update on unidades
      for each row execute function prueba_mutacion_no_permitida();`);
  try {
    const state = await snapshot();
    await assert.rejects(db.exec(correction), /dato fuera del costo Retail/);
    await db.exec('rollback');
    assert.deepEqual(await snapshot(), state);
  } finally {
    await db.exec('drop trigger prueba_mutacion_no_permitida on unidades; drop function prueba_mutacion_no_permitida()');
  }
});
